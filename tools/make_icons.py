"""
Builds src/lib/icons/glyphs.ts from the Home Base icon set in tools/icons (manifest.json plus
one SVG per icon). Run it again after dropping in a new version of the set:

    python3 tools/make_icons.py

Only drawing elements and their geometry survive (path, circle, ellipse, rect, line, polyline,
polygon; fills and strokes only as none or currentColor), so the glyphs are safe to inline.
"""
import json, pathlib, re, xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent
SET = ROOT / 'icons'
OUT = ROOT.parent / 'src' / 'lib' / 'icons' / 'glyphs.ts'

ELEMENTS = {'path', 'circle', 'ellipse', 'rect', 'line', 'polyline', 'polygon'}
# Not drawing: provenance and accessibility notes some tools add. Skipped with everything inside.
SKIPPED = {'metadata', 'title', 'desc'}
GEOMETRY = {'d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'y1', 'x2', 'y2', 'points', 'transform', 'fill-rule', 'clip-rule'}
PAINT = {'fill', 'stroke'}
NUMBERISH = re.compile(r'^[0-9eE.,\s+\-a-zA-Z()]*$')

def clean(svg_path):
    tree = ET.parse(svg_path)
    out = []
    for el in tree.getroot():
        tag = el.tag.split('}')[-1]
        if tag in SKIPPED:
            continue
        if tag not in ELEMENTS:
            raise SystemExit(f'{svg_path}: unexpected <{tag}>')
        attrs = []
        for key, value in el.attrib.items():
            key = key.split('}')[-1]
            if key in GEOMETRY and NUMBERISH.match(value):
                attrs.append(f'{key}="{value}"')
            elif key in PAINT and value in ('none', 'currentColor'):
                attrs.append(f'{key}="{value}"')
            elif key == 'stroke-width' and re.match(r'^[0-9.]+$', value):
                attrs.append(f'{key}="{value}"')
        out.append(f'<{tag} {" ".join(attrs)}/>')
    return ''.join(out)

manifest = json.loads((SET / 'manifest.json').read_text())
lines = [
    '// Generated by tools/make_icons.py from the Home Base icon set (tools/icons). Don’t edit by hand.',
    '// Each glyph is the inside of a 24 × 24 SVG drawn with a 1.5 stroke in currentColor.',
    '',
    'export const GLYPHS = {',
]
for entry in manifest:
    body = clean(SET / entry['path'])
    lines.append(f"\t{json.dumps(entry['name'])}: {json.dumps(body)},")
lines.append('} as const;')
lines.append('')
lines.append('export type GlyphId = keyof typeof GLYPHS;')
lines.append('')
OUT.write_text('\n'.join(lines))
print(f'{len(manifest)} glyphs → {OUT.relative_to(ROOT.parent)}')
